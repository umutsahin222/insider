CREATE TYPE notification_channel AS ENUM ('sms', 'email', 'push');
CREATE TYPE notification_status AS ENUM ('pending', 'processing', 'sent', 'failed', 'cancelled');

-- notifications is both the source of truth and the work queue (ADR-001).
CREATE TABLE notifications (
    id                  uuid PRIMARY KEY,               -- UUIDv7, generated by the application
    batch_id            uuid,
    idempotency_key     text,
    channel             notification_channel NOT NULL,
    recipient           text NOT NULL,
    content             text NOT NULL,
    priority            smallint NOT NULL DEFAULT 1 CHECK (priority BETWEEN 0 AND 2), -- 0 high, 1 normal, 2 low
    status              notification_status NOT NULL DEFAULT 'pending',
    scheduled_at        timestamptz,
    next_attempt_at     timestamptz NOT NULL DEFAULT now(),
    attempts            integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    max_attempts        integer NOT NULL CHECK (max_attempts > 0),
    locked_until        timestamptz,
    last_error          text,
    provider_message_id text,
    correlation_id      text NOT NULL DEFAULT '',
    trace_context       jsonb,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    sent_at             timestamptz,

    CONSTRAINT notifications_sent_has_timestamp CHECK (status <> 'sent' OR sent_at IS NOT NULL),
    CONSTRAINT notifications_processing_has_lease CHECK (status <> 'processing' OR locked_until IS NOT NULL)
);

-- Idempotency: a key may be used once; NULL keys are unrestricted.
CREATE UNIQUE INDEX notifications_idempotency_key_uq
    ON notifications (idempotency_key) WHERE idempotency_key IS NOT NULL;

-- Claim query: WHERE status='pending' AND channel=$1 AND next_attempt_at<=now() ORDER BY priority, next_attempt_at.
CREATE INDEX notifications_claim_idx
    ON notifications (channel, priority, next_attempt_at) WHERE status = 'pending';

-- Reaper: expired leases of crashed workers.
CREATE INDEX notifications_lease_idx
    ON notifications (locked_until) WHERE status = 'processing';

-- Keyset pagination (newest first), unfiltered and filtered by status.
CREATE INDEX notifications_created_idx        ON notifications (created_at DESC, id DESC);
CREATE INDEX notifications_status_created_idx ON notifications (status, created_at DESC, id DESC);

CREATE INDEX notifications_batch_idx ON notifications (batch_id) WHERE batch_id IS NOT NULL;

CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER notifications_set_updated_at
    BEFORE UPDATE ON notifications
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

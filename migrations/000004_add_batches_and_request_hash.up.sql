-- Fingerprint of the create request, so an idempotency key reused with a different body is
-- rejected instead of silently returning the original notification (ADR-006).
-- NULL for rows created before this migration; those replays cannot be verified.
ALTER TABLE notifications ADD COLUMN request_hash text;

-- A batch becomes a first-class record carrying the batch-level Idempotency-Key, so a retried
-- batch request is answered with the original batch instead of creating duplicates.
CREATE TABLE batches (
    id              uuid PRIMARY KEY,               -- UUIDv7, generated by the application
    idempotency_key text,
    request_hash    text,
    size            integer NOT NULL CHECK (size > 0),
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX batches_idempotency_key_uq
    ON batches (idempotency_key) WHERE idempotency_key IS NOT NULL;

-- Backfill batches that already exist so the foreign key below holds.
INSERT INTO batches (id, size, created_at)
SELECT batch_id, count(*), min(created_at)
FROM notifications
WHERE batch_id IS NOT NULL
GROUP BY batch_id;

ALTER TABLE notifications
    ADD CONSTRAINT notifications_batch_fk FOREIGN KEY (batch_id) REFERENCES batches (id);
